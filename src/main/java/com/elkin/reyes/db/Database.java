package com.elkin.reyes.db;
import java.sql.*;
public class Database {
  private static final String URL = System.getenv().getOrDefault("DB_URL", "jdbc:h2:file:./data/reyesdb;AUTO_SERVER=TRUE");
  public static Connection get() throws SQLException { return DriverManager.getConnection(URL, "sa", ""); }
  public static void init() throws SQLException {
    try { java.nio.file.Files.createDirectories(java.nio.file.Path.of("data")); } catch (java.io.IOException e) { throw new SQLException("No se pudo crear la carpeta data", e); }
    try (Connection c=get(); Statement s=c.createStatement()) {
      s.execute("CREATE TABLE IF NOT EXISTS caravanas (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, rey VARCHAR(20) NOT NULL UNIQUE, ofrenda VARCHAR(20) NOT NULL UNIQUE, origen VARCHAR(120) NOT NULL, camellos INT NOT NULL, estado VARCHAR(30) NOT NULL)");
      s.execute("CREATE TABLE IF NOT EXISTS paradas (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, caravana_id BIGINT NOT NULL, ciudad VARCHAR(120) NOT NULL, orden INT NOT NULL, dias_estancia INT NOT NULL, estado VARCHAR(30) NOT NULL, CONSTRAINT fk_caravana FOREIGN KEY(caravana_id) REFERENCES caravanas(id), CONSTRAINT uq_parada UNIQUE(caravana_id, orden))");
    }
  }
}
